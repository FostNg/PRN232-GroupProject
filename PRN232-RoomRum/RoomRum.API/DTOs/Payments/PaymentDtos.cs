using System.ComponentModel.DataAnnotations;

namespace RoomRum.API.DTOs.Payments;

/// <summary>
/// Tenant creates the booking-deposit order for a Confirmed appointment.
/// The amount is never supplied by the client: it is copied from the
/// appointment's DepositAmountSnapshot, which the database re-verifies.
/// </summary>
public class CreatePaymentRequest
{
    [Required]
    [Range(1, int.MaxValue)]
    public int AppointmentId { get; set; }

    [Required]
    [StringLength(30)]
    public string PaymentMethod { get; set; } = string.Empty;
}

/// <summary>
/// Simulated gateway result. A real VNPay integration would receive this from
/// its IPN callback instead; the MVP keeps the same shape so swapping the
/// provider later does not change the client contract.
/// </summary>
public class ConfirmPaymentRequest
{
    /// <summary>
    /// Gateway outcome. Only "Paid" and "Failed" are accepted from the client;
    /// "Pending" and "Cancelled" are server-controlled.
    /// </summary>
    [Required]
    [StringLength(20)]
    public string PaymentStatus { get; set; } = string.Empty;

    /// <summary>
    /// Gateway transaction reference. Required when PaymentStatus is "Paid";
    /// generated by the server when omitted.
    /// </summary>
    [StringLength(100)]
    public string? TransactionCode { get; set; }

    /// <summary>Required when PaymentStatus is "Failed".</summary>
    [StringLength(500)]
    public string? FailureReason { get; set; }
}

public sealed class PaymentResponse
{
    public int PaymentId { get; set; }

    public int AppointmentId { get; set; }

    public int ListingId { get; set; }

    public string ListingTitle { get; set; } = string.Empty;

    public decimal Amount { get; set; }

    public string PaymentPurpose { get; set; } = string.Empty;

    public string PaymentMethod { get; set; } = string.Empty;

    public string PaymentStatus { get; set; } = string.Empty;

    public string? TransactionCode { get; set; }

    public string? FailureReason { get; set; }

    public DateTime CreatedAt { get; set; }

    public DateTime? PaidAt { get; set; }

    public DateTime? UpdatedAt { get; set; }

    /// <summary>Current status of the appointment this payment belongs to.</summary>
    public string AppointmentStatus { get; set; } = string.Empty;

    /// <summary>Current status of the listing being reserved.</summary>
    public string ListingStatus { get; set; } = string.Empty;

    /// <summary>Server-computed permissions for the client's action buttons.</summary>
    public bool CanPay { get; set; }

    public bool CanRetry { get; set; }

    public bool CanCancel { get; set; }

    /// <summary>
    /// Simulated checkout URL the mobile app opens for the mock gateway screen.
    /// Null for real providers, where the client builds the URL from the
    /// gateway SDK instead.
    /// </summary>
    public string? CheckoutUrl { get; set; }
}

/// <summary>
/// Returned when a payment succeeds: the payment plus the listing and
/// appointment state the trigger changed as a side effect.
/// </summary>
public sealed class PaymentResultResponse
{
    public PaymentResponse Payment { get; set; } = null!;

    public string AppointmentStatus { get; set; } = string.Empty;

    public string ListingStatus { get; set; } = string.Empty;

    /// <summary>
    /// Number of other Pending appointments the database rejected because the
    /// listing is now Reserved.
    /// </summary>
    public int RejectedAppointments { get; set; }

    public string Message { get; set; } = string.Empty;
}
